"""Pure numerical ARM audit: no ROS import, owner, publishers or feedback.

Replays fixed validated joint targets through the existing 50/250 Hz bounded
RadianArmTrajectory. Historical initial positions are real; initial v/a=0 is
explicitly counterfactual. Additional motion states are generated by the actual
planner, never by resetting velocity to fake a stop.
"""
import argparse
import hashlib
import inspect
import json
import sys
import time
from pathlib import Path

import numpy as np


def main():
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('inputs','output','client_src','infra','profile'):
        p.add_argument('--'+name.replace('_','-'),type=Path,required=True)
    p.add_argument('--limit',type=int)
    args=p.parse_args();args.output.mkdir(parents=True,exist_ok=False)
    sys.path.insert(0,str(args.client_src))
    from f1dagger.robot_io import make_output
    from f1dagger.contract import ARM_NAMES
    import f1dagger.arm_output
    profile=json.loads(args.profile.read_text())
    bounds=np.array([profile['joint_limits_deg'][n] for n in ARM_NAMES])
    cases=json.loads(args.inputs.read_text())
    if args.limit:cases=cases[:args.limit]
    dt=.004;records=[];traces=[]

    def run(case,mode):
        out=make_output({'_infra_root':str(args.infra)})
        out.planner.set_limits(bounds)
        initial=np.asarray(case['initial_state16'],float)[:14]
        actions=np.asarray(case['actions'],float)[:,:14]
        anchor=np.asarray(case['anchor16'],float)[:14]
        # Existing right-only runtime replaces inactive left targets.
        actions[:,:7]=initial[:7];anchor[:7]=initial[:7]
        if mode=='one_point_rest':
            actions=actions[-1:];anchor=initial.copy()
        out.push(initial,0.,enabled=(False,False))
        clock=0.;prewarm=[]
        if mode=='one_point_generated_moving_state':
            warm=initial.copy();warm[7]+=2.
            for i in range(40):
                clock+=dt;out.push(warm,clock,enabled=(False,True));out.sample(clock)
                assert out.fault is None
            anchor=np.asarray(out.position).copy();actions=actions[-1:]
            prewarm=dict(position_deg=list(out.planner.position),velocity_deg_s=list(out.planner.velocity),
                acceleration_deg_s2=list(out.planner.acceleration))
        origin=clock;endpoint=len(actions)/30.;next_target=0.
        ticks=[];stopped=None;fault=None;modes={};initial_v=list(out.planner.velocity);initial_a=list(out.planner.acceleration)
        max_v=max_a=max_j=0.;previous_a=np.asarray(out.planner.acceleration)
        for index in range(1,int(np.ceil((endpoint+profile['settle_timeout_s'])/dt))+1):
            elapsed=index*dt;clock=origin+elapsed
            if elapsed+1e-12>=next_target:
                u=elapsed*30
                if u<1:target=(1-u)*anchor+u*actions[0]
                else:
                    position=min(u-1,len(actions)-1);lower=int(position);upper=min(lower+1,len(actions)-1)
                    target=(1-(position-lower))*actions[lower]+(position-lower)*actions[upper]
                out.push(target,clock,enabled=(False,True));next_target=elapsed+.02
            command=np.asarray(out.sample(clock))
            if out.fault:
                fault=out.fault;break
            planner=out.planner;native=planner._radians;cert=planner._certificate
            v=np.asarray(planner.velocity);a=np.asarray(planner.acceleration)
            max_v=max(max_v,float(abs(v).max()));max_a=max(max_a,float(abs(a).max()))
            max_j=max(max_j,float(abs(a-previous_a).max()/dt));previous_a=a
            assert max_v<=planner.max_velocity+1e-6
            assert max_a<=planner.max_acceleration+1e-6
            assert max_j<=planner.max_jerk+1e-4
            mode_name=planner.limit_diagnostics['mode'];modes[mode_name]=modes.get(mode_name,0)+1
            within_limits=bool(np.all(command>=bounds[:,0]-1e-10) and np.all(command<=bounds[:,1]+1e-10))
            wrist=max(1.025*abs(command[5])+abs(command[6]),1.025*abs(command[12])+abs(command[13]))
            assert within_limits and wrist<=110.5+1e-8
            certificate_ended=cert is not None and cert[1]>=cert[0].duration
            zero=bool(max(abs(np.asarray(native.velocity)[7:14]))<=1e-9 and max(abs(np.asarray(native.acceleration)[7:14]))<=1e-9)
            terminal_error=float(abs(command[7:14]-actions[-1,7:14]).max())
            if index%5==0 or (elapsed>=endpoint and certificate_ended and zero):
                ticks.append(dict(t_s=elapsed,position_right_deg=command[7:14].tolist(),velocity_right_deg_s=v[7:14].tolist(),
                    acceleration_right_deg_s2=a[7:14].tolist(),certificate_ended=certificate_ended,
                    certificate_duration_s=None if cert is None else cert[0].duration,
                    certificate_elapsed_s=None if cert is None else cert[1],mode=mode_name,terminal_error_deg=terminal_error))
            if elapsed>=endpoint and certificate_ended and zero and terminal_error<=planner.deadband:
                terminal=np.array(cert[0].at_time(cert[0].duration)[0][7:14]);tol=np.deg2rad(planner.deadband)
                assert np.allclose(terminal,np.deg2rad(actions[-1,7:14]),atol=tol,rtol=0)
                assert np.allclose(native.position[7:14],terminal,atol=tol,rtol=0)
                stopped=elapsed;break
        rec=dict(episode=case['episode'],request_id=case['request_id'],trial=case['trial'],mode=mode,
            points=len(actions),original_valid_new_points=case['valid_new_points'],endpoint_s=endpoint,
            initial_velocity_deg_s=initial_v,initial_acceleration_deg_s2=initial_a,generated_prewarm=prewarm,
            certified_stop=stopped is not None,stop_s=stopped,settle_after_endpoint_s=None if stopped is None else stopped-endpoint,
            fault=fault,last_terminal_error_deg=terminal_error,max_velocity_deg_s=max_v,max_acceleration_deg_s2=max_a,
            max_jerk_deg_s3=max_j,deadband_deg=out.planner.deadband,mode_counts=modes,
            limits_deg=[out.planner.max_velocity,out.planner.max_acceleration,out.planner.max_jerk])
        records.append(rec);traces.append(dict(case=rec,ticks=ticks));print(json.dumps(rec),flush=True)
        (args.output/'progress.json').write_text(json.dumps(records,indent=2)+'\n')

    for case in cases:run(case,'recorded_position_zero_initial_dynamics')
    for case in (cases[0],cases[-1]):
        run(case,'one_point_rest');run(case,'one_point_generated_moving_state')
    paths=[Path(__file__),args.inputs,args.profile,Path(f1dagger.arm_output.__file__),Path(inspect.getfile(make_output))]
    import pico_f1.arm_output,pico_f1.trajectory
    paths.extend([Path(pico_f1.arm_output.__file__),Path(pico_f1.trajectory.__file__)])
    summary=dict(primary_cases=len(cases),all_cases=len(records),certified_stops=sum(r['certified_stop'] for r in records),
        faults=sum(r['fault'] is not None for r in records),max_settle_after_endpoint_s=max((r['settle_after_endpoint_s'] for r in records if r['certified_stop']),default=None),
        real_robot_feedback_samples=0,robot_commands=0,publisher_instances=0,owner_instances=0,model_calls=0,
        limitations=['Pure numerical target-tracking and certificate test, no collision geometry or hardware follow-through validation.',
            'Main cases start at recorded measured q with counterfactual zero v/a; not a replay of unknown historical moving planner state.',
            'Dynamic counterexamples use actual planner-generated moving states, not measured historical velocities.',
            'No synthetic feedback is passed to the stop-proof engine; actual publication and fresh measured arrival remain untested.'],
        source_sha256={str(q):hashlib.sha256(q.read_bytes()).hexdigest() for q in paths})
    (args.output/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
    (args.output/'traces.json').write_text(json.dumps(traces)+'\n')
    print(json.dumps(summary),flush=True)


if __name__=='__main__':main()
